"""Public certificate download and local HTTPS setup instructions."""
import html
from pathlib import Path
from aiohttp import web


def add_setup_routes(app, directory, https_port=8443, address=None, setup_path='/camera-setup'):

    async def instructions(request):
        https_url = (f'https://{address}:{https_port}' if address else
                     str(request.url.with_scheme('https').with_port(https_port).with_path('/').with_query('')))
        return web.Response(content_type='text/html', text=f'''<!doctype html>
<html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>iPhone camera setup</title><body>
<h1>Enable your iPhone camera</h1>
<p>Keep your iPhone and computer on the same Wi-Fi. Open this page in Safari.</p>
<ol><li><a href="/root-ca.cer">Download the Surveillance Lab certificate</a>. Allow the download.</li>
<li>Open Settings &gt; General &gt; VPN &amp; Device Management.
Select the downloaded Surveillance Lab Local CA profile and tap Install.</li>
<li>Open Settings &gt; General &gt; About &gt; Certificate Trust Settings.
Enable full trust for <b>Surveillance Lab Local CA</b>.</li>
<li>Return to Safari and <a href="{html.escape(https_url)}">open Surveillance Lab over HTTPS</a>.
Create the room on your iPhone, then allow camera access. If you have already created the room
in this Safari tab, use Share camera.</li></ol>
<p>Everyone should use <b>{html.escape(https_url)}</b> to access this server.
The certificate must be trusted on each device that uses this HTTPS address.</p>
<p>Install only the certificate generated by your own computer. It authorizes this computer's
local certificate authority. Keep its private key private. You can remove the profile in
Settings &gt; General &gt; VPN &amp; Device Management when finished.</p>
<p><a href="https://support.apple.com/en-us/102390">Apple's certificate trust instructions</a></p>
</body></html>''')

    async def certificate(request):
        # Deliberately expose only the public CA certificate, never the key directory.
        certificate_path = Path(directory)/'root-ca.cer'
        if not certificate_path.is_file():
            raise web.HTTPNotFound(text='Local certificate is not ready. Start python local_https.py on the server computer.')
        return web.Response(body=certificate_path.read_bytes(),
                            content_type='application/x-x509-ca-cert',
                            headers={'Content-Disposition': 'attachment; filename="surveillance-lab-ca.cer"',
                                     'Cache-Control': 'no-store'})

    app.router.add_get(setup_path, instructions)
    app.router.add_get('/root-ca.cer', certificate)
    return app


def setup_app(directory, address, https_port):
    return add_setup_routes(web.Application(), directory, https_port, address, setup_path='/')
